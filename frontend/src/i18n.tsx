type I18nContextValue = {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: string) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    const stored = localStorage.getItem("buntu_language");
    return stored === "fr" || stored === "rn" || stored === "en" ? stored : "en";
  });

  const value = useMemo<I18nContextValue>(() => {
    function setLanguage(nextLanguage: Language) {
      localStorage.setItem("buntu_language", nextLanguage);
      setLanguageState(nextLanguage);
    }

    function t(key: string) {
      return dictionaries[language][key] || dictionaries.en[key] || key;
    }

    return { language, setLanguage, t };
  }, [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n must be used within I18nProvider");
  return context;
}

export function LanguageToggle() {
  const { language, setLanguage, t } = useI18n();
  const labels: Record<Language, string> = {
    en: t("english"),
    fr: t("french"),
    rn: t("kirundi"),
  };
  return (
    <label className="flex min-h-11 min-w-11 items-center gap-1 rounded-full bg-gray-100 px-3 py-2 text-xs font-black text-gray-600">
      <span className="hidden sm:inline">{t("language")}</span>
      <select
        value={language}
        onChange={(event) => setLanguage(event.target.value as Language)}
        className="max-w-[9rem] bg-transparent text-xs font-black outline-none"
        aria-label={t("language")}
      >
        <option value="en">{labels.en}</option>
        <option value="fr">{labels.fr}</option>
        <option value="rn">{labels.rn}</option>
      </select>
    </label>
  );
}
